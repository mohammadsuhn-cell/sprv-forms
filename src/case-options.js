export function composeCaseDescription(form) {
  if (!form.type || form.type === "واقعة أخرى" || !wording[form.type])
    return "";
  const prefix =
    {
      "مشاهدة مباشرة": "بالمشاهدة المباشرة، ",
      "إفادة منقولة": "بحسب إفادة منقولة، ",
      "تقرير مكتوب": "بحسب تقرير مكتوب، ",
      "مصدر آخر": "بحسب المصدر المحدد للواقعة، ",
    }[form.source] || "";
  const parts = [`${prefix}${wording[form.type]}.`];
  if (
    form.incidentDetail &&
    (incidentDetails[form.type] || []).includes(form.incidentDetail)
  )
    parts.push(`التفصيل المسجل: ${form.incidentDetail}.`);
  if (form.location) parts.push(`مكان الواقعة: ${form.location}.`);
  if (form.period) parts.push(`الحصة: ${form.period}.`);
  if (form.recurrence === "أول مرة مسجلة")
    parts.push("هذه أول مرة تُسجّل فيها الواقعة للطالب.");
  if (form.recurrence === "تكررت سابقًا")
    parts.push("سبق تسجيل الواقعة للطالب.");
  if (form.recurrence === "تكررت اليوم")
    parts.push("تكررت الواقعة خلال اليوم نفسه.");
  return parts.join(" ");
}
export function updateCaseChoice(form, key, value) {
  const next = { ...form, [key]: value };
  if (key === "type" && value !== form.type) {
    next.incidentDetail = "";
    next.recurrence = "";
  }
  if (
    !form.description?.trim() ||
    (form.descriptionGenerated &&
      form.description === form.descriptionGenerated)
  ) {
    next.description = composeCaseDescription(next);
    next.descriptionGenerated = next.description;
  }
  return next;
}
export const actionStatusLabel = (value) =>
  value === "مخطط للتنفيذ" ? "لم يُنفّذ بعد" : value;
export const isPendingAction = (value) =>
  actionStatusLabel(value) === "لم يُنفّذ بعد";
export const noAction = (value) =>
  ["لم يُتخذ إجراء بعد", "لم يُتخذ إجراء"].includes(value);
export function actionText(action, state) {
  const value = String(action || "").replace(
    / \(مخطط للتنفيذ\)$/u,
    " (لم يُنفّذ بعد)",
  );
  return value && isPendingAction(state) && !value.endsWith(" (لم يُنفّذ بعد)")
    ? `${value} (لم يُنفّذ بعد)`
    : value;
}
